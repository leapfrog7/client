const SOURCE_SHEET_COLUMN = "Source Sheet";

const isBlankValue = (value) => {
  if (value === null || value === undefined) return true;
  return String(value).trim() === "";
};

const isAutoGeneratedHeader = (value) => {
  if (value === null || value === undefined) return false;
  return /^Column\s+\d+$/i.test(String(value).trim());
};

const normaliseHeader = (header = "") => {
  return String(header).trim().replace(/\s+/g, " ");
};

const getHeaderKey = (header = "") => {
  return normaliseHeader(header).toLowerCase();
};

const getLooseHeaderKey = (header = "") => {
  return normaliseHeader(header)
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
};

const getUsableHeaders = (headers = [], rows = []) => {
  return headers
    .map((header, index) => ({
      label: normaliseHeader(header),
      index,
    }))
    .filter(({ label, index }) => {
      if (!label) return false;

      const columnHasData = rows.some((row) => !isBlankValue(row[index]));

      if (isAutoGeneratedHeader(label) && !columnHasData) {
        return false;
      }

      return true;
    });
};

const isBlankRowForHeaders = (row = [], usableHeaders = []) => {
  return usableHeaders.every(({ index }) => isBlankValue(row[index]));
};

const getUsableSheets = (sheets = []) => {
  return sheets.filter((sheet) => {
    const usableHeaders = getUsableHeaders(sheet.headers, sheet.rows);
    const hasRows = (sheet.rows || []).some(
      (row) => !isBlankRowForHeaders(row, usableHeaders),
    );

    return usableHeaders.length > 0 && hasRows;
  });
};

const buildMasterHeaders = (sheets = []) => {
  const seen = new Set();
  const masterHeaders = [SOURCE_SHEET_COLUMN];

  sheets.forEach((sheet) => {
    const usableHeaders = getUsableHeaders(sheet.headers, sheet.rows);

    usableHeaders.forEach(({ label }) => {
      const key = getHeaderKey(label);

      if (!seen.has(key)) {
        seen.add(key);
        masterHeaders.push(label);
      }
    });
  });

  return masterHeaders;
};

const buildCompatibilityReport = (allSheets = [], usableSheets = []) => {
  const sheetHeaderGroups = usableSheets.map((sheet) => {
    const usableHeaders = getUsableHeaders(sheet.headers, sheet.rows);

    return {
      sheetName: sheet.name,
      headers: usableHeaders.map(({ label }) => label),
      headerKeys: usableHeaders.map(({ label }) => getHeaderKey(label)),
    };
  });

  const headerFrequency = new Map();

  sheetHeaderGroups.forEach((sheet) => {
    sheet.headerKeys.forEach((key) => {
      headerFrequency.set(key, (headerFrequency.get(key) || 0) + 1);
    });
  });

  const totalUsableSheets = usableSheets.length;

  const commonHeaders = [];
  const differentHeaders = [];

  headerFrequency.forEach((count, key) => {
    const label =
      sheetHeaderGroups
        .flatMap((sheet) => sheet.headers)
        .find((header) => getHeaderKey(header) === key) || key;

    if (count === totalUsableSheets) {
      commonHeaders.push(label);
    } else {
      differentHeaders.push(label);
    }
  });

  const looseGroups = new Map();

  sheetHeaderGroups.forEach((sheet) => {
    sheet.headers.forEach((header) => {
      const looseKey = getLooseHeaderKey(header);

      if (!looseGroups.has(looseKey)) {
        looseGroups.set(looseKey, new Set());
      }

      looseGroups.get(looseKey).add(header);
    });
  });

  const possibleSimilarHeaders = Array.from(looseGroups.values())
    .map((group) => Array.from(group))
    .filter((group) => group.length > 1);

  let safetyLevel = "safe";
  let safetyMessage = "Headers look suitable for merging.";

  if (totalUsableSheets <= 1) {
    safetyLevel = "limited";
    safetyMessage = "Only one usable sheet was found.";
  } else if (differentHeaders.length > commonHeaders.length) {
    safetyLevel = "caution";
    safetyMessage =
      "Some sheets have different headers. They will be kept as separate columns.";
  } else if (possibleSimilarHeaders.length > 0) {
    safetyLevel = "review";
    safetyMessage =
      "Some headers look similar but are not identical. They have not been merged automatically.";
  }

  return {
    safetyLevel,
    safetyMessage,
    commonHeaders,
    differentHeaders,
    possibleSimilarHeaders,
    sheetHeaderGroups,
    sheetsFound: allSheets.length,
    usableSheets: usableSheets.length,
    skippedSheets: allSheets.length - usableSheets.length,
  };
};

export const mergeWorkbookSheets = (workbook) => {
  const sheets = workbook?.sheets || [];
  const usableSheets = getUsableSheets(sheets);
  const compatibility = buildCompatibilityReport(sheets, usableSheets);

  if (!usableSheets.length) {
    return {
      headers: [],
      rows: [],
      previewRows: [],
      compatibility,
      summary: {
        sheetsFound: sheets.length,
        sheetsMerged: 0,
        sheetsSkipped: sheets.length,
        rowsMerged: 0,
        columnsCreated: 0,
      },
    };
  }

  const masterHeaders = buildMasterHeaders(usableSheets);
  const masterHeaderKeys = masterHeaders.map((header) => getHeaderKey(header));
  const mergedRows = [];

  usableSheets.forEach((sheet) => {
    const usableHeaders = getUsableHeaders(sheet.headers, sheet.rows);

    const headerMap = new Map(
      usableHeaders.map(({ label, index }) => [getHeaderKey(label), index]),
    );

    (sheet.rows || []).forEach((row) => {
      if (isBlankRowForHeaders(row, usableHeaders)) return;

      const mergedRow = masterHeaders.map((header, masterIndex) => {
        if (masterIndex === 0) return sheet.name;

        const sourceIndex = headerMap.get(masterHeaderKeys[masterIndex]);

        if (sourceIndex === undefined) return "";

        return row[sourceIndex] ?? "";
      });

      mergedRows.push(mergedRow);
    });
  });

  return {
    headers: masterHeaders,
    rows: mergedRows,
    previewRows: mergedRows.slice(0, 50),
    compatibility,
    summary: {
      sheetsFound: sheets.length,
      sheetsMerged: usableSheets.length,
      sheetsSkipped: sheets.length - usableSheets.length,
      rowsMerged: mergedRows.length,
      columnsCreated: masterHeaders.length,
      commonHeaders: compatibility.commonHeaders.length,
      differentHeaders: compatibility.differentHeaders.length,
      possibleSimilarHeaders: compatibility.possibleSimilarHeaders.length,
    },
  };
};
