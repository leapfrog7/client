const isBlankValue = (value) => {
  if (value === null || value === undefined) return true;
  return String(value).trim() === "";
};

const cleanInvisibleCharacters = (value = "") => {
  return String(value)
    .replace(/\u00A0/g, " ") // non-breaking space
    .replace(/[\u200B-\u200D\uFEFF]/g, "") // zero-width characters
    .replace(/[\t\r\n]+/g, " ") // tabs and line breaks
    .replace(/\s+/g, " ") // repeated spaces
    .trim();
};

const cleanTextValue = (value) => {
  if (value === null || value === undefined) return "";

  if (value instanceof Date) return value;

  if (typeof value === "string") {
    return cleanInvisibleCharacters(value);
  }

  return value;
};

const isBlankRow = (row = []) => {
  return row.every(isBlankValue);
};

const isAutoGeneratedHeader = (value) => {
  if (value === null || value === undefined) return false;
  return /^Column\s+\d+$/i.test(String(value).trim());
};

const getBlankColumnIndexes = (headers = [], rows = []) => {
  const columnCount = headers.length;

  return Array.from({ length: columnCount }, (_, index) => index).filter(
    (columnIndex) => {
      const headerValue = headers[columnIndex];

      const headerIsBlankOrAutoGenerated =
        isBlankValue(headerValue) || isAutoGeneratedHeader(headerValue);

      const allRowsBlank = rows.every((row) => isBlankValue(row[columnIndex]));

      return headerIsBlankOrAutoGenerated && allRowsBlank;
    },
  );
};

const removeColumnsByIndex = (values = [], indexesToRemove = []) => {
  const removeSet = new Set(indexesToRemove);

  return values.filter((_, index) => !removeSet.has(index));
};

export const cleanSheetData = (sheet) => {
  if (!sheet) {
    return {
      headers: [],
      rows: [],
      summary: {
        rowsBefore: 0,
        rowsAfter: 0,
        blankRowsRemoved: 0,
        columnsBefore: 0,
        columnsAfter: 0,
        blankColumnsRemoved: 0,
        cellsCleaned: 0,
      },
    };
  }

  const originalHeaders = sheet.headers || [];
  const originalRows = sheet.rows || [];

  let cellsCleaned = 0;

  const cleanedHeaders = originalHeaders.map((value) => {
    const cleanedValue = cleanTextValue(value);

    if (String(cleanedValue) !== String(value ?? "")) {
      cellsCleaned += 1;
    }

    return cleanedValue;
  });

  const cleanedRows = originalRows.map((row) =>
    row.map((value) => {
      const cleanedValue = cleanTextValue(value);

      if (String(cleanedValue) !== String(value ?? "")) {
        cellsCleaned += 1;
      }

      return cleanedValue;
    }),
  );

  const nonBlankRows = cleanedRows.filter((row) => !isBlankRow(row));

  const blankColumnIndexes = getBlankColumnIndexes(
    cleanedHeaders,
    nonBlankRows,
  );

  const finalHeaders = removeColumnsByIndex(cleanedHeaders, blankColumnIndexes);

  const finalRows = nonBlankRows.map((row) =>
    removeColumnsByIndex(row, blankColumnIndexes),
  );

  return {
    headers: finalHeaders,
    rows: finalRows,
    previewRows: finalRows.slice(0, 50),
    summary: {
      rowsBefore: originalRows.length,
      rowsAfter: finalRows.length,
      blankRowsRemoved: originalRows.length - finalRows.length,
      columnsBefore: originalHeaders.length,
      columnsAfter: finalHeaders.length,
      blankColumnsRemoved: blankColumnIndexes.length,
      cellsCleaned,
    },
  };
};

